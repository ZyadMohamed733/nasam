# Generate a git-ignored xcconfig without printing credentials. Also run by Podfile.
require 'fileutils'
root = File.expand_path('..', __dir__)
env_file = File.join(root, '.env')
key = ENV['GOOGLE_MAPS_API_KEY']
if key.nil? && File.exist?(env_file)
  line = File.readlines(env_file).find { |entry| entry.start_with?('GOOGLE_MAPS_API_KEY=') }
  key = line&.split('=', 2)&.last&.strip&.delete_prefix('"')&.delete_suffix('"')
end
abort 'Set GOOGLE_MAPS_API_KEY in .env or the build environment.' unless key&.match?(/\A[A-Za-z0-9_-]+\z/)
output = File.join(__dir__, 'Flutter', 'MapsSecrets.xcconfig')
File.write(output, "// Generated by ios/maps_config.rb; do not commit.\nGOOGLE_MAPS_API_KEY = #{key}\n")
File.chmod(0600, output)
